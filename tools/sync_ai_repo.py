"""Mirror the AI build of gamelink into its own repository (github.com/Rapid421/bf2-gamelink-ai).

    python -I tools/sync_ai_repo.py [target-dir]      (default D:\\bf2-gamelink-ai)

Copies only what "build.bat ai" compiles (no menu code), plus the clients and the AI-build check, writes the AI
repo's build.bat, and regenerates docs/COMMANDS.md from src/commands_table.inc. The AI repo's own README.md,
AGENTS.md and LICENSE are not touched. Commit and push the target afterwards.
"""
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TARGET = sys.argv[1] if len(sys.argv) > 1 else r'D:\bf2-gamelink-ai'

FILES = [
    'src/main.cpp', 'src/gamelink_api.h', 'src/commands_table.inc', 'src/bots_logic.h', 'src/bots_logic.cpp',
    'src/ui/menu.h', 'src/ui/menu_none.cpp', 'src/ui/menu_state.h', 'src/ui/menu_state.cpp',
    'src/ui/settings.h', 'src/ui/settings.cpp',
    'client/gl.py', 'client/gl.ps1', 'client/gl.cmd', 'client/look.py',
    'harness/ai_check.py', 'tools/make_commands_table.py', '.gitignore',
]
DIRS = ['src/imgui']

BUILD = r'''@echo off
REM Build FrostyGameLink.dll - the AI build of gamelink: the command port on 127.0.0.1:31500 and every command,
REM no in-game menu. Needs Visual Studio 2019+ with the C++ desktop workload. Output: bin\FrostyGameLink.dll
setlocal
set "VSPATH=C:\Program Files\Microsoft Visual Studio\2022\Community"
set "VSWHERE=%ProgramFiles(x86)%\Microsoft Visual Studio\Installer\vswhere.exe"
if exist "%VSWHERE%" (
    for /f "usebackq delims=" %%i in (`"%VSWHERE%" -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath`) do set "VSPATH=%%i"
)
set "VCVARS=%VSPATH%\VC\Auxiliary\Build\vcvars64.bat"
if not exist "%VCVARS%" (
    echo vcvars64.bat not found at "%VCVARS%" - install Visual Studio with the C++ workload
    exit /b 1
)
call "%VCVARS%" >nul || exit /b 1
set "ROOT=%~dp0"
set "ROOT=%ROOT:~0,-1%"
if not exist "%ROOT%\bin" mkdir "%ROOT%\bin"
if not exist "%ROOT%\obj" mkdir "%ROOT%\obj"
REM /EHa: the structured-exception guards around engine memory need it. src\imgui: Dear ImGui 1.78 (MIT), used
REM only by the optional 'overlay' command.
cl /nologo /LD /O2 /MT /EHa /W3 /std:c++17 ^
   /DIMGUI_IMPL_WIN32_DISABLE_GAMEPAD /DGAMELINK_NO_MENU ^
   /I"%ROOT%\src\imgui" /I"%ROOT%\src" ^
   /Fe:"%ROOT%\bin\FrostyGameLink.dll" /Fo:"%ROOT%\obj\\" ^
   "%ROOT%\src\main.cpp" "%ROOT%\src\bots_logic.cpp" "%ROOT%\src\ui\menu_none.cpp" ^
   "%ROOT%\src\ui\menu_state.cpp" "%ROOT%\src\ui\settings.cpp" ^
   "%ROOT%\src\imgui\imgui.cpp" "%ROOT%\src\imgui\imgui_draw.cpp" "%ROOT%\src\imgui\imgui_widgets.cpp" ^
   "%ROOT%\src\imgui\imgui_impl_dx11.cpp" "%ROOT%\src\imgui\imgui_impl_win32.cpp" ^
   /link /DLL ws2_32.lib psapi.lib dbghelp.lib user32.lib d3dcompiler.lib gdi32.lib
exit /b %errorlevel%
'''


def commands_md():
    rows = []
    for line in open(os.path.join(ROOT, 'src', 'commands_table.inc'), encoding='utf-8'):
        m = re.match(r'\{"([^"]+)", "(.*)"\},$', line.strip())
        if m:
            rows.append((m.group(1), m.group(2).replace('\\"', '"').replace('\\\\', '\\')))
    out = ['# gamelink commands', '',
           'Every command the port at `127.0.0.1:31500` accepts, with the one-line description from the comment above '
           'its handler in `src/main.cpp` (read the handler for the details). Send one line, read one reply. The same '
           'list is available at run time: `help`, or `help <command>`.', '',
           '%d commands. Generated by `tools/sync_ai_repo.py` - do not edit by hand.' % len(rows), '',
           '| Command | Description |', '| --- | --- |']
    for verb, text in rows:
        out.append('| `%s` | %s |' % (verb, text.replace('|', '\\|')))
    return '\n'.join(out) + '\n'


def main():
    os.makedirs(TARGET, exist_ok=True)
    for rel in FILES:
        dst = os.path.join(TARGET, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy2(os.path.join(ROOT, rel), dst)
    for rel in DIRS:
        dst = os.path.join(TARGET, rel)
        if os.path.isdir(dst):
            shutil.rmtree(dst)
        shutil.copytree(os.path.join(ROOT, rel), dst)
    with open(os.path.join(TARGET, 'build.bat'), 'w', encoding='utf-8', newline='\r\n') as f:
        f.write(BUILD)
    os.makedirs(os.path.join(TARGET, 'docs'), exist_ok=True)
    with open(os.path.join(TARGET, 'docs', 'COMMANDS.md'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(commands_md())
    print('synced %d files + %s into %s' % (len(FILES), ', '.join(DIRS), TARGET))


if __name__ == '__main__':
    main()
