"""Writes src/commands_table.inc: every TCP verb with the one-line comment above its handler in src/main.cpp.

    python -I tools/make_commands_table.py

Run again after adding a verb; the table is committed, so a build never needs Python.
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'src', 'main.cpp')
OUT = os.path.join(ROOT, 'src', 'commands_table.inc')

# Handlers whose comment does not start with a usage line.
OVERRIDES = {
    'camera': 'camera - the render camera: position, left/up/forward axes and horizontal field of view.',
    'camlook': 'camlook <dyaw> <dpitch> - same as camturn.',
    'coords': 'coords [0|1] - an on-screen readout of the camera position.',
    'loadlevel': 'loadlevel <level-path> [mode] - ask the running game to load a level.',
    'ping': 'ping - answers "pong gamelink" when gamelink is attached.',
    'spl': "spl - inspect the frontend's single-player level loader.",
    'splset': 'splset - set fields on the single-player level loader (see spl).',
    'types': 'types - walk the type registry and report how many types it holds.',
    'ui': 'ui open|close|toggle|status|tab <name>|do <control> <value> - the F1 menu, for scripts and tests.',
    'viewmode': 'viewmode <n> - WorldRenderSettings.ViewMode on every live instance (0 = normal).',
    'watchdrive': 'watchdrive [0|1] - drive the camera from gamelink (free camera; see fly).',
}


def main():
    lines = open(SRC, encoding='utf-8').read().splitlines()
    table = {}
    for i, line in enumerate(lines):
        m = re.search(r'if \(command == "([a-z0-9_-]+)"', line)
        if not m:
            continue
        verbs = re.findall(r'command == "([a-z0-9_-]+)"', line)
        block = []
        k = i - 1
        while k >= 0 and lines[k].strip().startswith('//'):
            block.insert(0, lines[k].strip()[2:].strip())
            k -= 1
        for verb in verbs:
            if verb in table:
                continue
            usage = next((b for b in block if b.split(' ')[0] == verb or b.startswith(verb + ' ')), '')
            if not usage:
                usage = next((b for b in block if verb in b.split(' ')[0:3]), block[0] if block else verb)
            table[verb] = OVERRIDES.get(verb, usage)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by tools/make_commands_table.py from the comments above each handler in main.cpp.\n')
        for verb in sorted(table):
            text = table[verb].replace('\\', '\\\\').replace('"', '\\"')
            f.write('{"%s", "%s"},\n' % (verb, text))
    print('%d verbs -> %s' % (len(table), OUT))


if __name__ == '__main__':
    main()
